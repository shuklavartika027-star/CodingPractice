#include<iostream>
using namespace std;
int main()
{
    int a,b;
    cout<<"Enter a = "<<endl;
    cin>>a;
    cout<<"Enter b = "<<endl;
    cin>>b;
    cout<<"Sum of a and b is = "<<(a+b)<<endl;
    cout<<"Difference of a and b is = "<<(a-b)<<endl;
    cout<<"Multiplication of a and b is = "<<(a*b)<<endl;
    cout<<"Division of a and b is = "<<(a/b)<<endl;
    cout<<"Modular of a and b is = "<<(a%b)<<endl;
    return 0;

}